#!/usr/bin/env python3
"""Readable text on the light frame: per-sim colour fixes, generated from a contrast probe of the live builds.

    python3 tools/gen_contrast.py PROBE_DIR      # PROBE_DIR/*.json from harness/contrast_probe.mjs (one per sim)

Writes _generated/contrast.css: html[data-fsim-id="<id>"] <selector>{color:<fix> !important}, one rule per faint text
element found in the sidebar or stage (Explore-freely and Guided-Inquiry states) whose ground is LIGHT. The fix is the
SAME colour with only its perceptual lightness lowered (OKLCH: hue and chroma kept), just enough to reach WCAG 4.5:1
(3:1 for large text) plus a 0.3 margin, so teal stays teal and slate stays slate.

The rules live in the cascade layer `fermi.contrast`, declared FIRST: for !important, the first layer wins, so these
beat the A-look overrides without raising any specificity. Left out (logged), never guessed:
  - mixed:   the selector also matches elements of another colour;
  - inline:  the colour comes from a style="" attribute (a script sets it, e.g. colour-coded states: runtime part);
  - dynamic: the same selector shows different colours in different states;
  - none:    no darker shade of the hue reaches the target.
"""
import collections, json, pathlib, sys

KIT = pathlib.Path(__file__).resolve().parent.parent


def main(d):
    d = pathlib.Path(d); rules = collections.OrderedDict(); skipped = collections.Counter(); per = collections.Counter()
    for f in sorted(d.glob('*.json')):
        P = json.loads(f.read_text()); sid = P.get('id')
        if not sid: skipped['no id'] += 1; continue
        seen = collections.defaultdict(set); first = {}
        for x in P['free'] + P['gi']:
            seen[x['sel']].add(x['fg'])
            first.setdefault(x['sel'], x)
        for sel, x in first.items():
            why = 'dynamic' if len(seen[sel]) > 1 else 'mixed' if x['mixed'] else 'inline' if x['inline'] else 'none' if not x['tgt'] else None
            if why: skipped[why] += 1; continue
            rules[(sid, sel)] = (x['tgt'], x['fg'], x['cr'], x['text'])
            per[sid] += 1
    out = ['/* GENERATED by tools/gen_contrast.py from a contrast probe of the live builds. Do not edit by hand. */',
           '/* Faint text on the light frame -> the same colour, darker (OKLCH lightness only) to WCAG 4.5:1 (3:1 large). */']
    by = collections.defaultdict(list)
    for (sid, sel), (tgt, fg, cr, text) in rules.items(): by[sid].append(f'{sel}{{color:{tgt} !important}}')
    for sid, rr in by.items():   # one block per sim (CSS nesting; a browser without nesting keeps today's colours)
        out.append(f'html[data-fsim-id="{sid}"]{{' + ''.join(f'& {r}' for r in rr) + '}')
    (KIT / '_generated' / 'contrast.css').write_text('\n'.join(out) + '\n')
    with open(KIT / '_generated' / 'contrast-report.tsv', 'w') as o:   # what each rule fixes (kept out of the stylesheet)
        o.write('sim\tselector\twas\tcontrast\tnow\ttext\n')
        for (sid, sel), (tgt, fg, cr, text) in rules.items(): o.write(f'{sid}\t{sel}\t{fg}\t{cr}\t{tgt}\t{text}\n')
    print(f'rules {len(rules)} across {len(per)} sims · skipped {dict(skipped)}')


if __name__ == '__main__':
    main(sys.argv[1])
