#!/usr/bin/env python3
"""Check our tokens against the main app's design system and write TOKENS.md.

    python3 tools/parity.py            # needs `gh` (read access to Super-Stem/study-tools-v2)

For every token we declare whose name the main app also declares, the VALUE must be
identical (whitespace-normalised). Exit 1 on any mismatch. --fsim-* tokens are ours
(feature-scoped) and are listed with the main-app token they sit beside, if any.
"""
import pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
REPO, REF, BASE = 'Super-Stem/study-tools-v2', 'stage', 'frontend/src/design-system/_tokens'
MAIN_FILES = ['colors', 'typography', 'spacing', 'radius', 'elevation', 'motion', 'layout', 'fermi-horizon']
OURS = ['colors', 'typography', 'spacing', 'radius', 'elevation', 'motion', 'sim']

def decls(css):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    return {m.group(1): re.sub(r'\s+', ' ', m.group(2).strip()) for m in re.finditer(r'(?<![\w-])(--[a-z0-9-]+)\s*:\s*([^;]+);', css)}

def gh(path):
    return subprocess.run(['gh', 'api', '-H', 'Accept: application/vnd.github.raw', f'repos/{REPO}/contents/{path}?ref={REF}'],
                          capture_output=True, text=True, check=True).stdout

main = {}
for f in MAIN_FILES: main.update(decls(gh(f'{BASE}/{f}.css')))
canon = lambda v: re.sub(r'\s*,\s*', ',', v.replace("'", '"')).lower()
rows, bad = [], []
for f in OURS:
    for name, val in decls((ROOT / '_tokens' / f'{f}.css').read_text()).items():
        if name in main:
            same = canon(main[name]) == canon(val)
            if not same: bad.append(f'{name}: ours {val!r} vs main app {main[name]!r}')
            rows.append((f, name, val, 'same as main app' if same else f'MISMATCH (main app: `{main[name]}`)'))
        else:
            rows.append((f, name, val, 'sim-only (feature token)' if name.startswith('--fsim-') else 'NOT IN MAIN APP'))
            if not name.startswith('--fsim-'): bad.append(f'{name}: main-app-style name that the main app does not declare')

DIVERGE = {  # A-look values that differ from a main-app token of the same role (owner-locked; for the frontend team to reconcile)
    '--fsim-selected-bg': '--color-accent-subtle (#edf1fc)',
    '--fsim-accent-border': '--color-accent-border (rgba(65,105,225,0.30))',
    '--fsim-ok-text': '--color-success-text (#14532d) / --color-success (#16a34a)',
    '--fsim-bad-text': '--color-danger-text (#7a271a)',
    '--fsim-font-ui': '--font-sans (same value; separate name because every live sim redefines --font-sans as DM Sans)',
}
out = ['# fermi-sim.css · token reference', '',
       f'Generated by `tools/parity.py` against `{REPO}@{REF}:{BASE}`. Do not edit by hand.', '',
       '**Rule:** a token named like a main-app token has the main app\'s exact value (checked). '
       'Values the main app has no role for are `--fsim-*` feature tokens (main-app guidelines §6).', '',
       '| file | token | value | status |', '|---|---|---|---|']
out += [f'| {f} | `{n}` | `{v[:90]}{"…" if len(v) > 90 else ""}` | {s} |' for f, n, v, s in rows]
out += ['', '## Where the locked A look differs from a main-app token of the same role', '',
        '| sim token | sits beside main-app token |', '|---|---|'] + [f'| `{k}` | {v} |' for k, v in DIVERGE.items()]
out += ['', '## Known name collision', '',
        'Every live sim declares its own `--font-sans` (DM Sans) in unlayered CSS, which beats this sheet\'s layered '
        '`--font-sans`. The override layer therefore uses `--fsim-font-ui` for Inter. When Track R removes the sims\' '
        'own declaration, `--font-sans` takes effect and `--fsim-font-ui` retires.']
(ROOT / 'TOKENS.md').write_text('\n'.join(out) + '\n')
print(f'{len(rows)} tokens · {sum(1 for r in rows if r[3] == "same as main app")} identical to main app · '
      f'{sum(1 for r in rows if r[1].startswith("--fsim-"))} feature tokens · {len(bad)} problems')
for b in bad: print('  ' + b)
sys.exit(1 if bad else 0)
